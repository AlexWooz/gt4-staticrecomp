"""Pin a TASK-134 game build that starts from an earlier pin: docs/inputs/slice<N>-pcsx2.json or slice<N>-spec2.json.

The manifest copies the base pin of its target and replaces what the build changes: the executable, the EE library (rebuilt with a
profile of this build), and the VU1 and VU0 tables when they were regenerated by the TASK-134 emitter (docs/BUILD.md). The inputs the
base pin names stay verified by the Python tests against the files on disk.

The output file must not exist: a new slice always gets a new pin file (docs/inputs are history, never edited).

usage: pin_task134_build.py <slice> --base <slice> --target gt4|spec2 --exe <path under assets> --library <path under assets>
       [--vu1-dir <path under assets>] [--vu0-dir <path under assets>] --classification <text> --status <text>
       [--assets-root <folder>] [--date 2026-11-03]
"""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def identity(path):
    data = Path(path).read_bytes()
    return len(data), hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('slice', type=int)
    parser.add_argument('--base', type=int, required=True)
    parser.add_argument('--target', choices=('gt4', 'spec2'), required=True)
    parser.add_argument('--exe', required=True)
    parser.add_argument('--library', required=True)
    parser.add_argument('--vu1-dir')
    parser.add_argument('--vu0-dir')
    parser.add_argument('--classification', required=True)
    parser.add_argument('--status', required=True)
    parser.add_argument('--assets-root', type=Path, default=Path('C:/Antigravity/gt4-staticrecomp'))
    parser.add_argument('--date', default='2026-11-03')
    options = parser.parse_args()

    name = 'pcsx2' if options.target == 'gt4' else 'spec2'
    output = ROOT / f'docs/inputs/slice{options.slice}-{name}.json'
    if output.exists():
        raise SystemExit(f'{output} exists: a new slice gets a new pin file')
    pin = json.loads((ROOT / f'docs/inputs/slice{options.base}-{name}.json').read_text(encoding='utf-8'))
    assets = options.assets_root

    size, sha = identity(assets / options.exe)
    pin['runtime'] = {'path': options.exe, 'size_bytes': size, 'sha256': sha}
    size, sha = identity(assets / options.library)
    library = {'path': options.library, 'size_bytes': size, 'sha256': sha}
    pin['frozen_game_library'] = library
    pin['ee_library'] = dict(pin['ee_library'], path=options.library, size_bytes=size, sha256=sha)
    if options.vu1_dir:
        vu1 = dict(pin['vu1_aot'])
        vu1['generated_dir'] = options.vu1_dir
        vu1['generated_source_sha256'] = identity(assets / options.vu1_dir / 'vu1_generated.cpp')[1]
        vu1['generated_manifest_sha256'] = identity(assets / options.vu1_dir / 'manifest.json')[1]
        vu1['emitter'] = 'tools/vu_recomp of TASK-134 (2026-11-03), same image and entry list'
        pin['vu1_aot'] = vu1
    if options.vu0_dir:
        vu0 = dict(pin['vu0_aot'])
        vu0['generated_dir'] = options.vu0_dir
        vu0['table_sha256'] = identity(assets / options.vu0_dir / 'vu0_generated.cpp')[1]
        vu0['manifest_sha256'] = identity(assets / options.vu0_dir / 'manifest.json')[1]
        vu0['emitter'] = 'tools/vu_recomp of TASK-134 (2026-11-03), same image and entry list'
        vu0.pop('vu1_table', None)
        pin['vu0_aot'] = vu0
    pin['slice'] = options.slice
    pin['date'] = options.date
    pin['branch'] = 'task/134-game-code-optimization-study'
    pin['baseline_commit'] = f'slice{options.base}-{name}'
    pin['classification'] = options.classification
    pin['purpose'] = 'TASK-134: the CPU optimisation, second round.'
    pin['status'] = options.status
    output.write_text(json.dumps(pin, indent=2) + '\n', encoding='utf-8', newline='\n')
    print(f'{output.name}: exe {pin["runtime"]["sha256"][:16]} library {library["sha256"][:16]}')


if __name__ == '__main__':
    main()
