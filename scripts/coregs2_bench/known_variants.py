"""Writes native/hw_gs/core2/core2_known_variants.inc: the variants the launcher compiles before the first race (IN-507).

usage: known_variants.py <variants.bin> ...   (the files GT4_HW_SHADER_CACHE=<folder> leaves after a session)
The union of the lists, sorted, one key per row. A key holds draw state numbers only, no game data. A file with another
key size is refused: the keys changed, so the sessions must run again on the current build.
"""
import struct
import sys
from pathlib import Path

KEY_WORDS = 33
HEADER = struct.Struct('<8sQII')
TARGET = Path(__file__).resolve().parents[2] / 'native' / 'hw_gs' / 'core2' / 'core2_known_variants.inc'


def read_keys(path):
    data = Path(path).read_bytes()
    magic, _shader_set, key_words, count = HEADER.unpack_from(data)
    if magic != b'GT4VARS1' or key_words != KEY_WORDS or len(data) != HEADER.size + count * KEY_WORDS * 4:
        raise SystemExit(f'{path}: not a variant list of this build')
    words = struct.unpack_from(f'<{count * KEY_WORDS}I', data, HEADER.size)
    return {words[i:i + KEY_WORDS] for i in range(0, len(words), KEY_WORDS)}


keys = set()
for name in sys.argv[1:]:
    found = read_keys(name)
    print(f'{name}: {len(found)} keys, {len(found - keys)} new')
    keys |= found
if not keys:
    raise SystemExit('no keys')
rows = [','.join(f'0x{word:X}u' for word in key) + ',' for key in sorted(keys)]
TARGET.write_text('// Generated by scripts/coregs2_bench/known_variants.py (IN-507). One key per row.\n' + '\n'.join(rows) + '\n',
                  encoding='utf-8', newline='\n')
print(f'{TARGET}: {len(keys)} keys')
