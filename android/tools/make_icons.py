"""Builds the Android launcher icons of the game app from the PC icon's art (TASK-180, owner request 2026-11-05).

The PC game and the launcher use launcher/assets/brand/launcher.ico: the GT emblem in black on a white rounded square
(launcher/tools/make_brand.py, write_launcher_ico). Its highest-resolution source here is logo-gt4.png (the 1024 px
render of source/gt4-logo.svg that make_brand.py cuts the emblem from), so the icons are drawn from it with the same
crop, colours and proportions, only at the Android sizes:

- legacy icons (API < 26 and some launchers): mipmap-<density>/ic_launcher.png, the same rounded white square with the
  emblem filling 80% of the side, 48 dp;
- adaptive icon (API 26+): mipmap-anydpi-v26/ic_launcher.xml with a plain white background (values/ic_launcher_colors.xml)
  and mipmap-<density>/ic_launcher_foreground.png, the emblem on transparency, 108 dp with the emblem filling 80% of the
  72 dp visible part (it stays inside the 66 dp safe circle); the same layer is the themed (monochrome) icon.

Run from the repository root with Pillow:  private/tooling-venv/Scripts/python.exe android/tools/make_icons.py
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
LOGO = ROOT / "launcher" / "assets" / "brand" / "logo-gt4.png"
RES = ROOT / "launcher" / "crates" / "gt4l-tauri" / "gen" / "android" / "app" / "src" / "main" / "res"
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}
LEGACY_DP = 48
ADAPTIVE_DP = 108
ADAPTIVE_VISIBLE_DP = 72
TILE = (255, 255, 255, 255)  # make_brand.py LAUNCHER_TILE
CORNER = 0.22                # make_brand.py: corner radius 22% of the side
EMBLEM_SHARE = 0.80          # make_brand.py: the emblem fills 80% of the side
SUPERSAMPLE = 4              # the rounded tile is drawn at 4x and reduced, as make_brand.py does


def emblem_from_logo() -> Image.Image:
    """make_brand.py write_launcher_ico: the drawn area above the wordmark and left of the "4"."""
    logo = Image.open(LOGO).convert("RGBA")
    upper = logo.crop((0, 0, 850, 425))
    return upper.crop(upper.getchannel("A").getbbox())


def fitted(emblem: Image.Image, box: float) -> Image.Image:
    """The emblem scaled (Lanczos) to fit a box x box square at the final size, aspect kept. Drawn at the final size, not
    at the supersampled one: the 626 px source must never be enlarged first (the 256 px image of launcher.ico shows the
    emblem at 61% instead of 80% because make_brand.py thumbnails at 4x and Pillow's thumbnail never enlarges)."""
    ratio = min(box / emblem.width, box / emblem.height)
    return emblem.resize((max(1, round(emblem.width * ratio)), max(1, round(emblem.height * ratio))), Image.LANCZOS)


def legacy_icon(emblem: Image.Image, size: int) -> Image.Image:
    big = size * SUPERSAMPLE
    tile = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    ImageDraw.Draw(tile).rounded_rectangle((0, 0, big - 1, big - 1), radius=round(big * CORNER), fill=TILE)
    canvas = tile.resize((size, size), Image.LANCZOS)
    mark = fitted(emblem, size * EMBLEM_SHARE)
    canvas.alpha_composite(mark, ((size - mark.width) // 2, (size - mark.height) // 2))
    return canvas


def adaptive_foreground(emblem: Image.Image, size: int) -> Image.Image:
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    visible = size * ADAPTIVE_VISIBLE_DP / ADAPTIVE_DP
    mark = fitted(emblem, visible * EMBLEM_SHARE)
    canvas.alpha_composite(mark, ((size - mark.width) // 2, (size - mark.height) // 2))
    return canvas


def main() -> int:
    emblem = emblem_from_logo()
    for name, scale in DENSITIES.items():
        folder = RES / f"mipmap-{name}"
        folder.mkdir(parents=True, exist_ok=True)
        legacy_icon(emblem, round(LEGACY_DP * scale)).save(folder / "ic_launcher.png", optimize=True)
        adaptive_foreground(emblem, round(ADAPTIVE_DP * scale)).save(folder / "ic_launcher_foreground.png", optimize=True)
    adaptive = RES / "mipmap-anydpi-v26"
    adaptive.mkdir(parents=True, exist_ok=True)
    (adaptive / "ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by android/tools/make_icons.py: the PC icon's art (launcher.ico) as an adaptive icon. -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />\n'
        "</adaptive-icon>\n",
        encoding="utf-8",
    )
    values = RES / "values"
    values.mkdir(parents=True, exist_ok=True)
    (values / "ic_launcher_colors.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by android/tools/make_icons.py: the white tile of the PC icon (launcher.ico). -->\n"
        "<resources>\n"
        '    <color name="ic_launcher_background">#FFFFFF</color>\n'
        "</resources>\n",
        encoding="utf-8",
    )
    # The Tauri launcher (the Android app's main activity) needs the same art as a PNG for its context (bundle.icon in
    # tauri.android.conf.json); 512 px, the size Tauri's icon tooling starts from.
    tauri_icon = ROOT / "launcher" / "crates" / "gt4l-tauri" / "icons" / "icon.png"
    tauri_icon.parent.mkdir(parents=True, exist_ok=True)
    legacy_icon(emblem, 512).save(tauri_icon, optimize=True)
    print("Android icons written to", RES, "and", tauri_icon)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
